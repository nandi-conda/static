"""Turn a Site into one ultra app (LPython source).

Every page becomes a function of el()/attr()/text()/end() calls, and view()
renders the layout around the current page. The app's model is just `page`
(the index of the page on screen) and the search query; navigation is the GO
message, so moving between pages is an update() and a DOM patch, not a reload.

LPython's wasm backend keeps string literals byte for byte and does not
process escapes, so a literal must never contain a backslash or a newline,
and its quote must not appear inside it. `lit` picks a quote that fits and
splits out what cannot be written, emitting those characters with ch(code).
"""

import posixpath
import re
import sys
from urllib.parse import urlsplit

from .content import El, plain_text

# Messages. Islands have their own update(), so these never collide.
GO, POP, QUERY = 1, 2, 3

HEADER = '''\
# Generated by static. Do not edit: rebuild instead.
from lpython import i32, Const
from numpy import empty, int32
from ultra import (el, end, text, text_ref, attr, attr_ref, cls, cls_if, key,
                   on_click, on_input, on_escape, value_ref,
                   s_new, s_set, s_add, s_copy, s_clear, s_len, s_has)


@jscall
def ch(c: i32) -> None:
    """Text node holding one character (for ones a literal can't hold)."""
    pass

@jscall
def s_add_ch(h: i32, c: i32) -> None:
    pass

@jscall
def route() -> i32:
    """Index of the page the browser loaded."""
    pass

@jscall
def go(i: i32) -> None:
    """Point the address bar and the title at page i."""
    pass


GO: Const[i32] = {GO}
POP: Const[i32] = {POP}
QUERY: Const[i32] = {QUERY}
CLEAR: Const[i32] = 4
N: Const[i32] = {N}

page: i32 = 0
q: i32 = 0
sb: i32 = 0
titles: i32[{N}] = empty({N}, dtype=int32)
hay: i32[{N}] = empty({N}, dtype=int32)
'''


def py_str(s):
    """A literal for s, which holds no backslash or newline."""
    if '"' not in s:
        return f'"{s}"'
    return f"'{s}'"


def lit_parts(s):
    """Split s into ("lit", literal) and ("ch", code) parts."""
    out = []
    for tok in re.split(r"([\\\n\r])", s):
        if tok in ("\\", "\n", "\r"):
            out.append(("ch", ord(tok)))
        elif tok:
            if '"' in tok and "'" in tok:
                for k, piece in enumerate(tok.split('"')):
                    if k:
                        out.append(("ch", 34))
                    if piece:
                        out.append(("lit", py_str(piece)))
            else:
                out.append(("lit", py_str(tok)))
    return out


class Gen:
    def __init__(self, site, islands):
        self.site = site
        self.islands = islands
        self.lines = []

    def w(self, line, ind):
        self.lines.append("    " * ind + line)

    # ------------------------------------------------------------ strings

    def text(self, s, ind):
        for kind, v in lit_parts(s):
            self.w(f"text({v})" if kind == "lit" else f"ch({v})", ind)

    def attr(self, name, value, ind):
        parts = lit_parts(value)
        if len(parts) == 1 and parts[0][0] == "lit":
            self.w(f"attr({py_str(name)}, {parts[0][1]})", ind)
        elif not parts:
            self.w(f'attr({py_str(name)}, "")', ind)
        else:  # build it in the string store
            self.w('s_set(sb, "")', ind)
            for kind, v in parts:
                self.w(f"s_add(sb, {v})" if kind == "lit" else f"s_add_ch(sb, {v})", ind)
            self.w(f"attr_ref({py_str(name)}, sb)", ind)

    def set_str(self, h, s, ind):
        self.w(f'{h} = s_new()', ind)
        self.w(f's_set({h}, "")', ind)
        for kind, v in lit_parts(s):
            self.w(f"s_add({h}, {v})" if kind == "lit" else f"s_add_ch({h}, {v})", ind)

    # ------------------------------------------------------------ links

    def href(self, page, value):
        """(href, page index or None) for a link found on `page`."""
        u = urlsplit(value)
        if u.scheme or u.netloc or value.startswith("#") or not u.path:
            return value, None
        path = u.path
        if path.endswith(".md"):
            # relative to the markdown file, like on GitHub
            src = posixpath.normpath(posixpath.join(posixpath.dirname(page.src), path))
            target = next((p for p in self.site.pages if p.src == src), None)
            if target is None:
                print(f"warning: {page.src}: link to missing page {value}", file=sys.stderr)
                return value, None
        else:
            if not path.startswith("/"):
                path = posixpath.normpath(posixpath.join(page.url, path)) + "/"
            target = self.site.page_for(path if path.endswith("/") else path + "/")
            if target is None:  # a static file
                return (self.site.base + path.lstrip("/") if value.startswith("/") else value), None
        frag = "#" + u.fragment if u.fragment else ""
        url = self.site.base + target.url.lstrip("/") + frag
        return url, (None if frag else target.index)

    def link(self, label, i, ind, active=False):
        p = self.site.pages[i]
        self.w('el("a")', ind)
        self.attr("href", self.site.base + p.url.lstrip("/"), ind)
        self.w('attr("data-go", "")', ind)
        self.w(f"on_click(GO, {i})", ind)
        if active:
            self.w(f'cls_if("active", page == {i})', ind)
        self.text(label, ind)
        self.w("end()", ind)

    # ------------------------------------------------------------ tree

    def node(self, page, e, ind):
        if isinstance(e, str):
            self.text(e, ind)
            return
        if e.tag == "ultra-island":
            name = dict(e.attrs).get("name", "")
            if name not in self.islands:
                sys.exit(f"{page.src}: no island named {name!r} (islands/{name}.py)")
            self.w('el("div")', ind)
            self.w('cls("island")', ind)
            self.attr("data-island", name, ind)
            self.w("end()", ind)
            return
        self.w(f"el({py_str(e.tag)})", ind)
        go = None
        for k, v in e.attrs:
            if k == "class":
                for c in v.split():
                    self.w(f"cls({py_str(c)})", ind)
                continue
            if e.tag == "a" and k == "href":
                v, go = self.href(page, v)
            elif k == "src" and v.startswith("/"):
                v = self.site.base + v.lstrip("/")
            self.attr(k, v, ind)
        if go is not None:
            self.w('attr("data-go", "")', ind)
            self.w(f"on_click(GO, {go})", ind)
        for c in e.children:
            self.node(page, c, ind)
        self.w("end()", ind)

    def listing(self, page, ind):
        section = page.meta["list"].strip("/")
        items = [p for p in self.site.pages
                 if p.src.startswith(section + "/") and p is not page
                 and not p.src.endswith("index.md")]
        items.sort(key=lambda p: (p.date, p.title), reverse=True)
        self.w('el("ul")', ind)
        self.w('cls("listing")', ind)
        for p in items:
            self.w('el("li")', ind)
            if p.date:
                self.w('el("time")', ind + 1)
                self.text(p.date, ind + 1)
                self.w("end()", ind + 1)
            self.link(p.title, p.index, ind + 1)
            desc = p.meta.get("description")
            if desc:
                self.w('el("p")', ind + 1)
                self.text(desc, ind + 1)
                self.w("end()", ind + 1)
            self.w("end()", ind)
        self.w("end()", ind)

    def page_fn(self, p):
        self.w(f"def page_{p.index}() -> None:", 0)
        self.w('el("article")', 1)
        self.w('cls("page")', 1)
        self.w('el("h1")', 1)
        self.text(p.heading, 1)
        self.w("end()", 1)
        if p.date or p.tags:
            self.w('el("p")', 1)
            self.w('cls("meta")', 1)
            if p.date:
                self.w('el("time")', 1)
                self.text(p.date, 1)
                self.w("end()", 1)
            for t in p.tags:
                self.w('el("span")', 1)
                self.w('cls("badge")', 1)
                self.w('cls("secondary")', 1)
                self.text(t, 1)
                self.w("end()", 1)
            self.w("end()", 1)
        for c in p.body.children:
            self.node(p, c, 1)
        if p.meta.get("list"):
            self.listing(p, 1)
        self.w("end()", 1)
        self.lines.append("")
        self.lines.append("")

    # ------------------------------------------------------------ app

    def nav_pages(self):
        nav = self.site.config.get("nav")
        if nav:
            out = []
            for u in nav:
                p = self.site.page_for(u if u.endswith("/") else u + "/")
                if p is None:
                    sys.exit(f"site.toml: nav entry {u!r} matches no page")
                out.append(p)
            return out
        top = [p for p in self.site.pages
               if p.index > 0 and (p.src.count("/") == 0 or p.src.endswith("/index.md")
                                   and p.src.count("/") == 1)]
        top.sort(key=lambda p: (int(p.meta.get("order", 100)), p.title))
        return [self.site.pages[0]] + top

    def generate(self):
        site = self.site
        n = len(site.pages)
        self.lines.append(HEADER.format(GO=GO, POP=POP, QUERY=QUERY, N=n))

        self.w("def init() -> None:", 0)
        self.w("global page, q, sb", 1)
        self.w("page = route()", 1)
        self.w("q = s_new()", 1)
        self.w("sb = s_new()", 1)
        self.w("h: i32", 1)
        for p in site.pages:
            self.set_str("h", p.title, 1)
            self.w(f"titles[{p.index}] = h", 1)
            words = [p.title, p.meta.get("description", ""), " ".join(p.tags)]
            if site.config.get("search", "full") == "full":
                words.append(p.text)
            words = " ".join(words)
            self.set_str("h", words, 1)
            self.w(f"hay[{p.index}] = h", 1)
        self.lines.append("\n")

        self.w("def update(msg: i32, arg: i32) -> None:", 0)
        self.w("global page", 1)
        self.w("if msg == GO:", 1)
        self.w("page = arg", 2)
        self.w("s_clear(q)", 2)
        self.w("go(arg)", 2)
        self.w("elif msg == POP:", 1)
        self.w("page = arg", 2)
        self.w("s_clear(q)", 2)
        self.w("elif msg == QUERY:", 1)
        self.w("s_copy(q, 0)", 2)
        self.w("elif msg == CLEAR:", 1)
        self.w("s_clear(q)", 2)
        self.lines.append("\n")

        for p in site.pages:
            self.page_fn(p)

        self.w("def search() -> None:", 0)
        self.w("i: i32", 1)
        self.w("hits: i32 = 0", 1)
        self.w('el("div")', 1)
        self.w('cls("search")', 1)
        self.w('el("input")', 1)
        self.w('cls("input")', 1)
        self.w('attr("type", "search")', 1)
        self.w('attr("placeholder", "Search")', 1)
        self.w('attr("aria-label", "Search pages")', 1)
        self.w("value_ref(q)", 1)
        self.w("on_input(QUERY)", 1)
        self.w("on_escape(CLEAR, 0)", 1)
        self.w("end()", 1)
        self.w("if s_len(q) > 0:", 1)
        self.w('el("ul")', 2)
        self.w('cls("results")', 2)
        self.w("for i in range(N):", 2)
        self.w("if s_has(hay[i], q) == 1:", 3)
        self.w("hits += 1", 4)
        self.w('el("li")', 4)
        self.w("key(i)", 4)
        self.w('el("a")', 4)
        self.w('attr("data-go", "")', 4)
        self.w("on_click(GO, i)", 4)
        self.w("text_ref(titles[i])", 4)
        self.w("end()", 4)
        self.w("end()", 4)
        self.w("if hits == 0:", 2)
        self.w('el("li")', 3)
        self.w('cls("none")', 3)
        self.w('text("No matches")', 3)
        self.w("end()", 3)
        self.w("end()", 2)
        self.w("end()", 1)
        self.lines.append("\n")

        self.w("def view() -> None:", 0)
        self.w('el("header")', 1)
        self.w('cls("site-header")', 1)
        self.w('el("a")', 1)
        self.w('cls("brand")', 1)
        self.attr("href", site.base, 1)
        self.w('attr("data-go", "")', 1)
        self.w("on_click(GO, 0)", 1)
        self.text(site.title, 1)
        self.w("end()", 1)
        self.w('el("nav")', 1)
        for p in self.nav_pages():
            self.link(p.meta.get("nav_title", "Home" if p.index == 0 else p.title),
                      p.index, 1, active=True)
        self.w("end()", 1)
        self.w("search()", 1)
        self.w("end()", 1)
        self.w('el("main")', 1)
        self.w('cls("site-main")', 1)
        for p in site.pages:
            kw = "if" if p.index == 0 else "elif"
            self.w(f"{kw} page == {p.index}:", 1)
            self.w(f"page_{p.index}()", 2)
        self.w("end()", 1)
        footer = site.config.get("footer", "Built with static: markdown compiled to WebAssembly by ultra.")
        self.w('el("footer")', 1)
        self.w('cls("site-footer")', 1)
        self.text(footer, 1)
        self.w("end()", 1)
        return "\n".join(self.lines) + "\n"


def generate(site, islands):
    return Gen(site, islands).generate()
